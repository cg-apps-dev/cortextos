#!/usr/bin/env bash
# Fixture for the negative-control axes in SPEC-single-voice-bootstrap-conflict.md.
# (The axis count is NOT stated anywhere in this header. The RUN numbers them in its
#  output - that is the only count, and it cannot go stale. See HOW TO ADD AN AXIS.)
#
# This is a TEST, not an example. The rest of that spec is prose that needs a reader;
# this fires. It runs the real failed search from 2026-07-25 that was published
# fleet-wide as "the line does not exist" — a false zero that hid a bootstrap
# contradiction in 24 files for hours.
#
# The point: THE FIRST TWO CONTROLS PASS ON THAT ZERO. Only varying the pattern
# catches it. If this script ever fails, the rule it encodes has stopped holding.
#
# Usage:  bash playbooks/fleet/check-negative-is-measured.sh
# Exit:   0 = every axis still behaves as documented
#         1 = an axis no longer discriminates; the spec's guidance is stale
#
# ---------------------------------------------------------------------------
# WHAT THIS FIXTURE DOES NOT COVER  (read this before trusting the list)
#
# THESE AXES ARE THE ONES THAT HAVE BITTEN US. THERE ARE CERTAINLY OTHERS.
# A six-row artifact with no boundary line gets read as the complete set, and
# that misreading is itself one of the defects catalogued here: a freshly-fixed
# axis manufactures unearned confidence about the axes you have not met yet
# (claude-dev-agent, 2026-07-25: "true count, no cap" was true about the cap
# and false about completeness -- one axis controlled, completeness claimed).
#
# Saying "this list is incomplete" is not enough. A prose admission is read as
# modesty; the ROWS are read as the artifact. So the boundary has to be
# ACTIONABLE:
#
# HOW TO ADD AN AXIS -- do this the next time a clean-looking result is wrong:
#   1. Write the probe that FALSELY PASSED, verbatim, with its real exit code.
#   2. Write the probe that CATCHES it, and assert BOTH exit codes via expect().
#   3. Add one line naming the real incident and date, so a later reader can
#      tell a live axis from a hypothetical one.
#   4. Bump the axis number in the section comment. Do NOT restate the total
#      anywhere -- a count in prose goes stale the moment someone appends, and
#      this header said "three-part" while the file held six for two commits.
#
# EVERY AXIS HERE RETURNS SOMETHING THAT LOOKS CLEAN. That is the whole selection
# criterion, and it is why the list is not enumerated in this header: run the file
# and read the section labels, which are generated by the checks themselves.
# (This block previously said "ALL SIX" and listed six, four lines under an
#  instruction reading "Do NOT restate the total anywhere". A seventh axis was
#  added and the list stayed at six -- the residue sat OUTSIDE the edited span,
#  which is the same span-replace defect this file exists to catch, committed by
#  the author of the seventh axis. Deleted rather than corrected: a corrected
#  list is a second site that goes stale on the eighth.
#  IT REACHED THE EIGHTH. This working copy still carried the six-item list while
#  the file held eight, on a branch, uncommitted -- so the prediction in the line
#  above came true in the very artifact that made it, and was caught only by
#  diffing against main before committing. THE STALE COUNT OUTLIVED TWO FIXES.)
# ---------------------------------------------------------------------------

set -uo pipefail
cd "$(dirname "$0")/../.." || exit 1
F=templates/agent/AGENTS.md
fail=0

say() { printf '%-58s %s\n' "$1" "$2"; }
expect() { # expect <label> <actual-exit> <wanted-exit> <note>
  if [ "$2" = "$3" ]; then say "$1" "exit $2  ok   $4"
  else say "$1" "exit $2  FAIL wanted $3 -- $4"; fail=1; fi
}

[ -f "$F" ] || { echo "fixture corpus missing: $F"; exit 1; }
echo "corpus: $F"
echo

# --- 1. RAN? -----------------------------------------------------------------
# An invalid pattern prints "0 matches" on some engines and exits 2. A valid
# pattern that is genuinely absent exits 1. Unpiped: $? in a pipeline is the
# LAST command's, so | head or | wc -l substitutes the formatter's exit.
grep -q 'NEVER LEAVE THE USER' "$F"; a=$?
expect "1. RAN?      all-caps form (the original search)" "$a" 1 "valid pattern, reads as absent -> PASSES"

# --- 2. REACHED? -------------------------------------------------------------
# A positive control proves the corpus is reachable and the scope is right.
grep -q 'Telegram message arrives' "$F"; b=$?
expect "2. REACHED?  positive control, different string" "$b" 0 "corpus reachable -> PASSES"

# --- 3. RIGHT PATTERN? -------------------------------------------------------
# Neither check above can see that the pattern itself is wrong, because a
# positive control uses a DIFFERENT pattern. Vary YOUR OWN string instead:
# drop the case, drop a word, take the distinctive middle fragment.
grep -qi 'NEVER LEAVE THE USER' "$F"; c=$?
expect "3. PATTERN?  same string, case dropped" "$c" 0 "ABSENCE WAS FALSE"
grep -q 'leave the user as the last' "$F"; d=$?
expect "3. PATTERN?  distinctive middle fragment" "$d" 0 "ABSENCE WAS FALSE"
grep -q 'last person to have sent' "$F"; e=$?
expect "3. PATTERN?  leading words dropped" "$e" 0 "ABSENCE WAS FALSE"

# --- 4. LINE CONTINUATION ----------------------------------------------------
# Second axis of the same defect: A PATTERN THAT DOES NOT MATCH THE TEXT FOR A
# REASON THE PATTERN CANNOT SEE. Axis 1 was case. This is line structure.
# Real instance 2026-07-25: the-analyst grepped its own cron scripts for bus calls
# ending in >/dev/null and got ZERO across three files -- because the redirect sits
# on a CONTINUATION LINE after a backslash. Joining continuations first gave 12.
# Caught by implausibility (it knew it had written them), not by design.
CONT="$(mktemp)"; trap 'rm -f "$CONT"' EXIT
printf '%s\n' 'cortextos bus log-event action thing info \' '    --meta "{}" >/dev/null 2>&1' > "$CONT"
grep -q 'log-event.*>/dev/null' "$CONT"; f=$?
expect "4. CONTINUATION  single-line grep over a wrapped call" "$f" 1 "reads as absent -> FALSE ZERO"
# Join continuations, then match. This is the fix, not a second pattern.
perl -0pe 's/\\\s*\n\s*/ /g' "$CONT" | grep -q 'log-event.*>/dev/null'; g=$?
expect "4. CONTINUATION  continuations joined first" "$g" 0 "ABSENCE WAS FALSE"

# --- 5. SPECIFIC BUT NOT SENSITIVE -------------------------------------------
# Third axis, and the one no negative control can reach: A NEGATIVE CONTROL IS THE
# SPECIFICITY TEST. It proves the detector does not fire on the wrong thing. It
# says nothing about whether the detector fires on the RIGHT thing.
# So a pattern that matches NOTHING AT ALL passes every negative control offered
# and catches nothing -- perfectly specific, perfectly blind.
grep -q 'zzz_this_string_exists_nowhere' "$F"; h=$?
expect "5. SENSITIVITY   a pattern that matches nothing" "$h" 1 "passes as 'no false positives'"
# The sensitivity test is a KNOWN-PRESENT needle. It is a different question and
# needs a different fixture; specificity cannot answer it.
grep -q 'Telegram message arrives' "$F"; i=$?
expect "5. SENSITIVITY   known-present needle (the real test)" "$i" 0 "detector can actually fire"

# --- 6. NO OUTPUT IS NOT A RESULT --------------------------------------------
# Fourth axis, and the only one the other five cannot reach, because it has no
# value to inspect. THREE INSTANCES ON 2026-07-25 (the-orchestrator once,
# the-analyst twice): an unquoted glob or a guessed path, zsh answers
# "no matches found", the command NEVER RUNS, and a conclusion gets published
# under it. One nearly closed a durability task on the finding that the tree it
# protects does not exist; there were 14 tracked files.
#
# ALL THREE PRODUCED NO OUTPUT AND A CONCLUSION ANYWAY. NOT ONE PRODUCED A WRONG
# VALUE -- which is why the class lands on careful people: THERE IS NOTHING TO
# CHECK. A wrong number invites arithmetic; an empty result invites a conclusion.
# It is also exactly where the night's one working detector goes blind:
# IMPLAUSIBILITY CANNOT FIRE ON ABSENCE, BECAUSE ABSENCE HAS NO MAGNITUDE TO BE
# ABSURD ABOUT (the-orchestrator).
GLOBDIR="$(mktemp -d)"; trap 'rm -f "$CONT"; rm -rf "$GLOBDIR"' EXIT
printf 'needle_is_here\n' > "$GLOBDIR/real.txt"
# THE FIRST DRAFT OF THIS AXIS FAILED ITS OWN FIXTURE, AND THE FAILURE IS THE
# FINDING. It asserted exit 1, because the three live instances were in zsh. Run
# under bash it returns 2. A PROBE WRITTEN FOR ONE SHELL AND RUN IN ANOTHER IS
# NOT A MEASUREMENT (SPEC-single-voice:426) -- committed while encoding a rule
# about unmeasured searches. Measured, both shells, rather than assumed:
#   bash: unmatched glob passes the literal through -> grep exit 2 = FILE ERROR
#   zsh:  "no matches found", THE COMMAND NEVER RUNS  -> exit 1
#   grep on a real file, genuinely absent             -> exit 1
# SO THE DANGER IS ZSH-SPECIFIC AND THE FLEET RUNS ZSH: zsh returns EXACTLY the
# code that means "searched, found nothing". bash at least returns a distinct 2 --
# a signal that exists and that nobody checks. In zsh there is no difference to
# ignore. That is why all three instances tonight were zsh.
grep -q 'needle_is_here' "$GLOBDIR"/*.nosuchext 2>/dev/null ; j=$?
expect "6. NO OUTPUT     bash: never-searched is exit 2, NOT 1" "$j" 2 "distinguishable -- if you check for 2"
if command -v zsh >/dev/null 2>&1; then
  zsh -c "grep -q needle_is_here '$GLOBDIR'/*.nosuchext 2>/dev/null" >/dev/null 2>&1; z=$?
  expect "6. NO OUTPUT     zsh: never-searched is exit 1 = 'absent'" "$z" 1 "IDENTICAL to a real zero"
fi
grep -q 'zzz_absent_needle' "$GLOBDIR"/real.txt 2>/dev/null ; m=$?
expect "6. NO OUTPUT     a REAL search that found nothing" "$m" 1 "same 1 zsh returns for never-ran"
# The fix is not a better pattern. It is asserting the search had something to
# search: resolve the target list FIRST and refuse when it is empty.
FILES=( "$GLOBDIR"/*.txt )
if [ ! -e "${FILES[0]}" ]; then k=2; else grep -q 'needle_is_here' "${FILES[@]}"; k=$?; fi
expect "6. NO OUTPUT     target list resolved and asserted first" "$k" 0 "ABSENCE WAS FALSE"
# And the guard itself must be exercised: an empty target list returns 2
# (UNMEASURED), never 1 (absent). Same shape as assert-the-value-not-the-key and
# as the positive control on the same pid -- prove the thing ran before reading it.
EMPTY=( "$GLOBDIR"/*.nosuchext )
if [ ! -e "${EMPTY[0]}" ]; then l=2; else grep -q 'needle_is_here' "${EMPTY[@]}"; l=$?; fi
expect "6. NO OUTPUT     empty target list returns UNMEASURED not absent" "$l" 2 "2 != 1: unmeasured != clean"

# --- 7. YOUR grep MAY NOT BE grep ---------------------------------------------
# The widest axis here, because it invalidates a CATEGORY of negative result
# rather than one shape of mistake. In an interactive agent session `grep` is not
# /usr/bin/grep -- it is a SHELL FUNCTION from the claude-home shell snapshot that
# execs `ARGV0=ugrep <claude> -G ...` (ugrep 7.5.0). Measured 2026-07-25 on the
# identical pattern and file, by two agents independently:
#     bare grep      0        <- the wrapper
#     command grep   115      <- /usr/bin/grep
#     grep -F        115
# So EVERY REGEX CLAIM AN AGENT MAKES WITH BARE grep IS A UGREP CLAIM, under a
# metacharacter set nobody is writing for. The divergence is not between agents;
# it is between an agent and the human-authored doc it is following. Five wrong
# mechanisms were published for that zero before anyone ran `type grep`.
#
# THIS SCRIPT CANNOT REPRODUCE THAT DIRECTLY -- `bash script.sh` does not inherit
# a zsh shell function, so `grep` here is already /usr/bin/grep. Stating that
# rather than writing a check that silently cannot fire (axis 5's own warning).
# What IS reproducible everywhere is the class: the SAME literal, present in the
# file, found by one engine and missed by another.
LIT="$(mktemp)"; trap 'rm -f "$CONT" "$LIT"; rm -rf "$GLOBDIR"' EXIT
printf 'path is state/${CTX_AGENT_NAME}/crons.json here\n' > "$LIT"
NEEDLE='state/${CTX_AGENT_NAME}/crons.json'
# NOTE: no `|| echo 0` here. `grep -c` PRINTS a count and EXITS 1 when that count
# is zero, so `$(grep -c ... || echo 0)` appends a second 0 and the variable
# becomes "0\n0" -- which fails an equality test against 0 while looking correct
# in the output. This axis failed its own first run on exactly that, which is the
# third time a new axis here has caught its own author before review did.
n1=$(grep -c  "$NEEDLE" "$LIT" 2>/dev/null); n1=${n1:-0}
expect "7. WHICH grep?   default engine finds the literal" "$n1" 1 "present, and found"
n2=$(grep -Ec "$NEEDLE" "$LIT" 2>/dev/null); n2=${n2:-0}
expect "7. WHICH grep?   -E on the SAME string, same file" "$n2" 0 "FALSE ZERO -- engine, not content"
n3=$(grep -Fc "$NEEDLE" "$LIT" 2>/dev/null); n3=${n3:-0}
expect "7. WHICH grep?   -F is the answer to both" "$n3" 1 "literal means literal"
# THE RULE, and it needs no knowledge of which binary you have:
# ON ANY NEGATIVE THAT MATTERS, RE-RUN WITH -F (or `command grep`). IF THE COUNT
# MOVES, THE PATTERN WAS NEVER LITERAL. Here 1 vs 0 vs 1 -- the disagreement is
# the signal, and you get it without diagnosing the engine at all.

# ---------------------------------------------------------------------------
# AXIS 8: TYPE.  Is the value a MEASUREMENT, or a SENTENCE ABOUT a measurement?
#
# Incident 2026-07-26, the-orchestrator, FOUR times in one night on one file
# (the-analyst/workspace/throughput-series.jsonl). Every error had the same
# root: a number was read out of a data file WITHOUT CHECKING ITS TYPE, and
# every one of those numbers lived inside a hand-authored string.
#   - "8 -> 8; gross_inflow 0"            -> read as gross_inflow=0. It is prose.
#   - "413 -> 413 (3rd consecutive flat)" -> read as a 3-window series. One row.
#   - each row's own "FLAT"               -> read as flat ACROSS rows. It moved:
#     604 -> 588 -> 588 -> 588 -> 611, i.e. -16 then +23, +7 net. And the 07-21
#     row embeds the CONCLUSION "5th+ window flat = zero real launches" while the
#     value was 611 two windows later.
#
# THAT THIRD ONE IS THE WORST AND IT IS NOT A LIE ANYWHERE. Every "FLAT" is a
# TRUE statement about WITHIN-window movement; the quantity moved BETWEEN
# windows. So no reader is ever contradicted, and the trend is the opposite of
# what reading the rows gives you. Hence the second clause of the rule below:
# A CLAIM THAT IS TRUE ABOUT ITS OWN ROW CAN STILL BE FALSE ABOUT THE SERIES.
# A severity ruling was published on it, retracted, republished on a second
# string, and retracted again. THE SECOND RETRACTION IS THE POINT: a correction
# reads as already-checked, so nobody audits the evidence you move TO.
#
# This axis is immune to the check the rest of this file is about. You cannot
# catch it by varying a pattern, and you cannot catch it by MISMATCH between two
# agents either -- mismatch needs two independent measurements, and a field only
# one row carries has exactly one (meta-compliance-agent, same night). What DOES
# fire is type + per-row presence. That is the replacement, not a gap.
# FIXTURE PROVENANCE, and why a synthetic one is acceptable HERE.
# security-agent's asymmetry rule (2026-07-26): A POSITIVE CONTROL NEEDS A REAL
# NEEDLE, because a synthetic may lack the real shape. A NEGATIVE CONTROL NEEDS
# INPUT YOU CAN PROVE IS CLEAN, AND THE ONLY INPUT YOU CAN PROVE IS CLEAN IS INPUT
# YOU BUILT. This axis's rows are constructed, so the rule says validate them
# against the real artifact -- done, on the-analyst/workspace/throughput-series.jsonl
# (57 rows), and ALL THREE PROBES MATCH THE FIXTURE'S EXIT CODES:
#   probe1 scrape-by-name on the real last row   -> FOUND "0"        exit 0  (matches)
#   probe2 require-numeric on the real last row  -> ABSENT           exit 1  (matches)
#   probe3 rows carrying posted_static_other     -> 1 of 57          exit 1  (matches)
# So the synthetic HAS the real shape and the axis is validated against a real
# needle rather than only against its own construction.
#
# BUT A SYNTHETIC VALIDATED AGAINST A REAL ARTIFACT IS VALIDATED AT A POINT IN TIME
# (security-agent). The synthetic is FROZEN and the artifact is NOT. If that file
# gains a field, changes a type, or starts emitting the numeric where it now emits
# the string, THIS FIXTURE KEEPS PASSING against a shape that no longer exists --
# and it will pass MORE confidently, because it carries a note saying it was checked
# against the real thing. That is the relational-detector rule turned on a fixture:
# A STALE SCAN GETS RE-RUN AND SELF-CORRECTS; A STALE FIXTURE KEEPS PASSING AND
# ACTIVELY ARGUES THAT IT IS CURRENT.
#
# SO THE VALIDATION IS STAMPED. Re-run the three-probe comparison if these move:
#   throughput-series.jsonl at validation time: 57 rows, 86755 bytes, mtime 2026-07-25T05:33:47Z
# If the live file differs from those, THIS PROVENANCE NOTE IS OLDER THAN THE DATA
# and the "validated against a real needle" claim above is unverified, not false.
TYPEFIX="$(mktemp)"
cat > "$TYPEFIX" <<'JSONL'
{"date":"2026-07-23","measured":{"gross_inflow":2},"static_posts":{"posted_to_sheet_raw":"611->611 FLAT"}}
{"date":"2026-07-24","measured":{"gross_inflow":6}}
{"date":"2026-07-25","VERDICT":{"qc_review_static":"8 -> 8; gross_inflow 0, gross_exits 0","posted_static_other":"413 -> 413 (3rd consecutive window flat)"}}
JSONL

# The probe that FALSELY PASSED, verbatim in shape: scrape a number for the field
# name off the latest row and use it. Finds "0". Exit 0. Looks like a reading.
p1=0; python3 - "$TYPEFIX" <<'PY' || p1=1
import json,sys,re
row=[json.loads(l) for l in open(sys.argv[1]) if l.strip()][-1]
blob=json.dumps(row)
m=re.search(r'gross_inflow[^0-9-]*(-?\d+)',blob)
sys.exit(0 if m else 1)
PY
expect "8. TYPE?        scrape the number by field name" "$p1" 0 "finds 0 -> READS AS A MEASUREMENT"

# The probe that CATCHES it: require the field to exist AS A NUMBER on that row.
p2=0; python3 - "$TYPEFIX" <<'PY' || p2=1
import json,sys
row=[json.loads(l) for l in open(sys.argv[1]) if l.strip()][-1]
def walk(o,p=""):
    if isinstance(o,dict):
        for k,v in o.items(): yield from walk(v,f"{p}.{k}" if p else k)
    else: yield p,o
nums=[(p,v) for p,v in walk(row)
      if p.endswith("gross_inflow") and isinstance(v,(int,float)) and not isinstance(v,bool)]
sys.exit(0 if nums else 1)
PY
expect "8. TYPE?        require it to BE a number on that row" "$p2" 1 "ABSENT -- the 0 was prose"

# And the consecutiveness claim: count rows that actually CARRY the field. A
# string asserting "3rd consecutive window" about rows that do not contain the
# field is unfalsifiable -- the only evidence for the history is the phrase.
p3=0; python3 - "$TYPEFIX" <<'PY' || p3=1
import json,sys
rows=[json.loads(l) for l in open(sys.argv[1]) if l.strip()]
n=sum(1 for r in rows if "posted_static_other" in json.dumps(r))
sys.exit(0 if n >= 3 else 1)   # the string claims 3 windows; do 3 rows carry it?
PY
expect "8. TYPE?        do 3 rows back the '3 consecutive' claim" "$p3" 1 "1 of 3 -- IT ASSERTS ITS OWN HISTORY"
rm -f "$TYPEFIX"
# THE RULE, both clauses:
#   A STRING CONTAINING NUMBERS IS A CLAIM, NOT A MEASUREMENT --
#   AND A CLAIM THAT IS TRUE ABOUT ITS OWN ROW CAN STILL BE FALSE ABOUT THE SERIES.
# Before a value carries a decision, assert (a) its TYPE is numeric and (b) it is
# PRESENT ON EVERY ROW YOU CLAIM TO DIFF. Both are one line and either alone would
# have stopped all four of that night's errors.
#
# Note which way the corrected reading went: not "less certain" but OPPOSITE --
# the inflow series was RISING out of a zero run, and the quantity every row
# called flat had MOVED. A NARRATED SERIES DOES NOT FAIL TOWARD CAUTION.
#
# And this is structural, not a lapse. Sweeping that file's 332 key paths
# (the-analyst, same night): 19 exist ON THE LAST ROW ONLY -- including the whole
# verdict block -- and 149 are orphaned on one old row. UN-DIFFABLE BY
# CONSTRUCTION is the normal case for narrated fields, not the exception.

echo
# Derive the summary from the accumulated failure flag, NOT by re-checking the
# values. An earlier version re-tested $a/$b/$c here and printed HOLDS while
# exiting 1 -- a label asserting a conclusion its own exit code contradicted,
# which is the exact defect this spec documents. The summary must not be able to
# disagree with the exit status.
if [ "$fail" = 0 ]; then
  echo "HOLDS: two controls passed on a zero that was wrong. Only the pattern check caught it."
else
  echo "STALE: the documented behaviour no longer reproduces. Re-read the spec before trusting its guidance."
fi
exit "$fail"
